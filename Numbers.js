//Exponent
let a = 156e5;
let b = 156e-5;
console.log(a);
console.log(b);
//Integer precision
let x = 9999999999999999;
let y = 999999999999999;
console.log(x);
console.log(y);
//Floating point precision
let xi = 0.22 + 0.12;
let yi = (0.22 * 10 + 0.12 * 10) / 10;
console.log(xi);
console.log(yi);
//Adding two strings
let ai = 10;
let bi = 20;
let ci = ai + bi;
console.log(ci);
//Concatenating two strings
let xy = "10";
let yx = "20";
let xz = xy + yx;
console.log(xz);
//Numeric Strings
let c = "100" / "10";
let d = "100" * "10";
let e = "100" + "10";
let f = "100" - "10";
console.log(c);
console.log(d);
console.log(e);
console.log(f);